import {
  ChangeDetectionStrategy,
  Component,
  EventEmitter,
  Input,
  OnChanges,
  OnDestroy,
  Output,
} from '@angular/core';
import { Subscription } from 'rxjs';
import { TranslocoPipe } from '@jsverse/transloco';
import { Bill } from '../../types/bill';
import { UserPreferences } from '../../types/userPreferences';
import { DEFAULT_PREFERENCES } from '../../services/preferences.service';
import { BillService } from '../../services/bill.service';
import { MoneyPipe } from '../../formatting/money.pipe';
import { LocalDatePipe } from '../../formatting/local-date.pipe';
import {
  BillStatus,
  TranslatedText,
  getAmount,
  getDueText,
  getStatus,
  isEstimated,
} from '../bill-status';

// One-off bills can be removed from the row, after an inline confirmation.
@Component({
  selector: 'app-bill-row',
  standalone: true,
  imports: [TranslocoPipe, MoneyPipe, LocalDatePipe],
  templateUrl: './bill-row.component.html',
  changeDetection: ChangeDetectionStrategy.Eager,
  styleUrl: './bill-row.component.css'
})
export class BillRowComponent implements OnChanges, OnDestroy {
  @Input({ required: true }) bill!: Bill;
  @Input({ required: true }) today!: Date;
  @Input() preferences: UserPreferences = DEFAULT_PREFERENCES;
  @Output() removed = new EventEmitter<Bill>();

  status: BillStatus = 'pending';
  dueText: TranslatedText | null = null;
  amount: number | null = null;
  estimated = false;
  isConfirmingRemove = false;
  isRemoving = false;
  removeError = false;

  private subscription?: Subscription;

  constructor(private billService: BillService) {}

  ngOnChanges(): void {
    this.status = getStatus(this.bill, this.today);
    this.dueText = getDueText(this.bill, this.today);
    this.amount = getAmount(this.bill);
    this.estimated = isEstimated(this.bill);
  }

  ngOnDestroy(): void {
    this.subscription?.unsubscribe();
  }

  get isVariable() {
    return this.bill.amountType !== 'Fixed';
  }

  // Bills generated by a recurring bill go away with it instead.
  get isOneOff() {
    return this.bill.recurringBillId === null;
  }

  askRemove() {
    this.isConfirmingRemove = true;
    this.removeError = false;
  }

  cancelRemove() {
    this.subscription?.unsubscribe();
    this.isConfirmingRemove = false;
    this.isRemoving = false;
    this.removeError = false;
  }

  confirmRemove() {
    const bill = this.bill;
    this.isRemoving = true;
    this.removeError = false;
    this.subscription = this.billService.delete(bill.id).subscribe({
      next: () => {
        this.isRemoving = false;
        this.isConfirmingRemove = false;
        this.removed.emit(bill);
      },
      error: () => {
        this.isRemoving = false;
        this.removeError = true;
      },
    });
  }
}
